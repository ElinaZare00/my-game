# بازی آزمون چهارگزینه‌ای بدون تعریف تابع
# در این برنامه، کاربر می‌تواند بازی را شروع کند، دوباره بازی کند یا از برنامه خارج شود.

# امتیاز پاسخ درست
BONUS = 10

# مقدار کسر امتیاز برای پاسخ اشتباه
PENALTY = 3

# فهرست سؤال‌ها؛ هر سؤال شامل متن سؤال، گزینه‌ها و پاسخ صحیح است.
questions = [
    (
        "What's the best CMS?",
        ["A: WordPress", "B: Joomla", "C: Drupal", "D: Headless"],
        "A",
    ),
    (
        "What's the best programming language?",
        ["A: Python", "B: JavaScript", "C: Java", "D: C++"],
        "A",
    ),
    (
        "What's the best database?",
        ["A: MySQL", "B: PostgreSQL", "C: MongoDB", "D: SQLite"],
        "B",
    ),
]

# حلقه بی‌نهایت برای نمایش دوباره منو تا وقتی که کاربر گزینه خروج را انتخاب کند
while True:
    print("\n====== منوی اصلی ======")
    print("1. شروع بازی / شروع دوباره")
    print("2. خروج")

    # دریافت انتخاب کاربر؛ strip فاصله‌های ابتدا و انتهای ورودی را حذف می‌کند
    choice = input("یک گزینه انتخاب کنید (1 یا 2): ").strip()

    # اگر کاربر گزینه 1 را وارد کند، بازی شروع می‌شود
    if choice == "1":
        # با هر بار شروع یا شروع دوباره، امتیاز و تعداد پاسخ‌های درست صفر می‌شوند
        score = 0
        user_corrects = 0

        print("\n--- بازی شروع شد ---")

        # پیمایش سؤال‌ها؛ در هر دور متن سؤال، گزینه‌ها و پاسخ صحیح جدا می‌شوند
        for question, options, correct_answer in questions:
            print(f"\n{question}")

            # نمایش تک‌تک گزینه‌های سؤال فعلی
            for option in options:
                print(option)

            # دریافت پاسخ، حذف فاصله‌های اضافی و تبدیل حروف به بزرگ
            user_answer = input(
                "پاسخ شما (A/B/C/D): "
            ).strip().upper()

            # بررسی پاسخ کاربر با پاسخ صحیح
            if user_answer == correct_answer:
                print("پاسخ درست است!")
                score += BONUS          # اضافه کردن 10 امتیاز
                user_corrects += 1       # افزایش تعداد پاسخ‌های درست به اندازه یک
            else:
                # در پاسخ اشتباه، پاسخ صحیح نمایش داده و 3 امتیاز کم می‌شود
                print(
                    f"پاسخ اشتباه است! پاسخ صحیح {correct_answer} است."
                )
                score -= PENALTY

        # محاسبه درصد پاسخ‌های درست از کل سؤال‌ها
        percentage = user_corrects / len(questions) * 100

        # نمایش نتیجه نهایی بازی
        print("\n--- نتیجه بازی ---")
        print(f"امتیاز نهایی شما: {score}")
        print(f"تعداد پاسخ‌های درست: {user_corrects}")
        print(f"درصد پاسخ‌های درست: {percentage:.1f}%")

    # اگر کاربر گزینه 2 را انتخاب کند، پیام خروج نمایش داده می‌شود
    elif choice == "2":
        print("خدانگهدار!")
        break  # پایان حلقه و خروج از برنامه

    # اگر ورودی نه 1 باشد و نه 2، پیام خطا نمایش داده می‌شود و منو دوباره می‌آید
    else:
        print("گزینه نامعتبر است؛ لطفاً 1 یا 2 وارد کنید.")
