# ============================================================
# بازی آزمون چهارگزینه‌ای (Multiple-Choice Quiz Game)
# هدف برنامه:
# 1) نمایش یک منو برای شروع/شروع دوباره بازی یا خروج
# 2) نمایش پرسش‌ها و گزینه‌های هر پرسش
# 3) بررسی پاسخ کاربر و محاسبه امتیاز نهایی
# 4) محاسبه تعداد پاسخ‌های درست و درصد موفقیت
# ============================================================

# امتیازی که برای هر پاسخ درست به کاربر داده می‌شود.
BONUS = 10

# امتیازی که برای هر پاسخ نادرست از امتیاز کاربر کم می‌شود.
PENALTY = 3

# فهرست پرسش‌های بازی:
# هر پرسش یک تاپل (tuple) شامل سه بخش است:
# بخش اول: متن پرسش
# بخش دوم: فهرست گزینه‌ها
# بخش سوم: حرف گزینه صحیح
# ترتیب هر تاپل به این شکل است:
# (متن پرسش، گزینه‌ها، پاسخ صحیح)
questions = [
    (
        "What's the best CMS?",
        ["A: WordPress", "B: Joomla", "C: Drupal", "D: Headless"],
        "A",  # پاسخ صحیح پرسش اول
    ),
    (
        "What's the best programming language?",
        ["A: Python", "B: JavaScript", "C: Java", "D: C++"],
        "A",  # پاسخ صحیح پرسش دوم
    ),
    (
        "What's the best database?",
        ["A: MySQL", "B: PostgreSQL", "C: MongoDB", "D: SQLite"],
        "B",  # پاسخ صحیح پرسش سوم
    ),
]


def play_game():
    """
    تابع اجرای یک دور بازی.
    هر بار که این تابع فراخوانی شود، امتیاز و تعداد پاسخ‌های درست
    از ابتدا محاسبه می‌شوند؛ بنابراین شروع دوباره، بازی را از نو آغاز می‌کند.
    """

    # امتیاز اولیه کاربر در ابتدای هر دور بازی صفر است.
    score = 0

    # شمارنده تعداد پاسخ‌های درست نیز در ابتدای بازی صفر است.
    user_corrects = 0

    # پیام شروع بازی نمایش داده می‌شود.
    # نویسه \\n باعث ایجاد یک خط خالی قبل از پیام می‌شود.
    print("\\n--- Game started ---")

    # حلقه for تمام پرسش‌های موجود در فهرست questions را یکی‌یکی می‌خواند.
    # در هر تکرار:
    # question       = متن پرسش فعلی
    # options        = فهرست گزینه‌های همان پرسش
    # correct_answer = حرف پاسخ صحیح همان پرسش
    for question, options, correct_answer in questions:

        # متن پرسش فعلی را نمایش می‌دهیم.
        print(f"\\n{question}")

        # این حلقه تو‌در‌تو، تمام گزینه‌های پرسش فعلی را نمایش می‌دهد.
        for option in options:
            print(option)

        # پاسخ کاربر دریافت می‌شود.
        # input(...) ورودی را به شکل رشته دریافت می‌کند.
        # strip() فاصله‌های ابتدا و انتهای ورودی را حذف می‌کند.
        # upper() حروف انگلیسی را به حروف بزرگ تبدیل می‌کند؛
        # بنابراین a و A به یک شکل بررسی می‌شوند.
        user_answer = input("Your choice (A/B/C/D): ").strip().upper()

        # بررسی می‌کنیم که پاسخ کاربر با پاسخ صحیح برابر است یا نه.
        if user_answer == correct_answer:

            # اگر پاسخ صحیح باشد، پیام مناسب نمایش داده می‌شود.
            print("Correct!")

            # به امتیاز فعلی کاربر، مقدار BONUS یعنی 10 اضافه می‌شود.
            score += BONUS

            # تعداد پاسخ‌های صحیح یک واحد افزایش می‌یابد.
            user_corrects += 1

        else:
            # اگر پاسخ کاربر با پاسخ صحیح برابر نباشد،
            # این بخش اجرا می‌شود و پاسخ صحیح را نمایش می‌دهد.
            print(f"Incorrect! The correct answer is {correct_answer}.")

            # به‌ازای پاسخ نادرست، مقدار PENALTY یعنی 3 از امتیاز کم می‌شود.
            score -= PENALTY

    # پس از پایان حلقه و پاسخ‌گویی به تمام پرسش‌ها، درصد موفقیت محاسبه می‌شود.
    # تعداد پاسخ‌های درست بر تعداد کل پرسش‌ها تقسیم و در 100 ضرب می‌شود.
    # len(questions) تعداد پرسش‌های فهرست را برمی‌گرداند.
    percentage = user_corrects / len(questions) * 100

    # عنوان بخش نتایج نمایش داده می‌شود.
    print("\\n--- Game results ---")

    # امتیاز نهایی کاربر نمایش داده می‌شود.
    print(f"Your final score is: {score}")

    # تعداد پرسش‌هایی که کاربر درست پاسخ داده است نمایش داده می‌شود.
    print(f"You answered {user_corrects} questions correctly.")

    # درصد موفقیت با یک رقم اعشار نمایش داده می‌شود.
    # :.1f یعنی عدد اعشاری با یک رقم بعد از ممیز چاپ شود.
    print(f"Percentage: {percentage:.1f}%")


def main():
    """
    تابع اصلی برنامه.
    منو را پیوسته نمایش می‌دهد تا کاربر بازی را شروع/دوباره شروع کند
    یا با انتخاب گزینه خروج، از برنامه خارج شود.
    """

    # حلقه while با شرط True تا زمانی ادامه دارد که با break متوقف شود.
    while True:

        # عنوان منوی اصلی نمایش داده می‌شود.
        print("\\n====== MAIN MENU ======")

        # گزینه اول برای شروع بازی یا اجرای دوباره آن است.
        print("1. Start / Restart game")

        # گزینه دوم برای خروج از برنامه است.
        print("2. Exit")

        # انتخاب کاربر دریافت می‌شود.
        # strip() فاصله‌های اضافی ابتدا و انتهای ورودی را حذف می‌کند.
        choice = input("Choose an option (1/2): ").strip()

        # اگر کاربر عدد 1 را وارد کند، یک دور بازی اجرا می‌شود.
        if choice == "1":
            play_game()

            # پس از پایان بازی، اجرای تابع play_game تمام می‌شود
            # و برنامه به حلقه while در main برمی‌گردد؛
            # بنابراین منو دوباره نمایش داده می‌شود.

        # اگر کاربر عدد 2 را وارد کند، باید از برنامه خارج شویم.
        elif choice == "2":

            # پیام خداحافظی نمایش داده می‌شود.
            print("Goodbye!")

            # دستور break حلقه while را متوقف می‌کند
            # و باعث پایان اجرای تابع main می‌شود.
            break

        else:
            # اگر ورودی نه "1" باشد و نه "2"، این پیام نمایش داده می‌شود.
            # سپس حلقه ادامه پیدا می‌کند و منو دوباره نشان داده می‌شود.
            print("Invalid choice. Please enter 1 or 2.")


# این شرط بررسی می‌کند که آیا فایل مستقیماً اجرا شده است یا نه.
# اگر برنامه مستقیماً اجرا شود، مقدار __name__ برابر "__main__" است
# و تابع main() فراخوانی می‌شود.
# اگر این فایل در فایل پایتون دیگری import شود، main() خودکار اجرا نمی‌شود.
if __name__ == "__main__":
    main()
